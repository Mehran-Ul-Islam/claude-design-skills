import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { palette, type, space, radius, shadow, material, glassBase } from "./tokens.js";

const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());

const colorVars = (theme, pad = "  ") =>
  Object.entries(palette[theme]).map(([k, v]) => `${pad}--${kebab(k)}: ${v};`).join("\n");

const glassVars = (theme, pad = "  ") =>
  Object.entries(material)
    .map(([k, m]) => `${pad}--glass-bg-${k}: rgba(${glassBase[theme]}, ${m.alpha});`)
    .join("\n") +
  `\n${pad}--glass-edge: ${theme === "light" ? "rgba(255,255,255,0.6)" : "rgba(255,255,255,0.14)"};`;

const staticVars = [
  `  --font: ${type.family};`,
  ...Object.entries(type.scale).flatMap(([k, t]) => [
    `  --text-${k}-size: ${t.size};`,
    `  --text-${k}-leading: ${t.leading};`,
    `  --text-${k}-tracking: ${t.tracking};`,
    `  --text-${k}-weight: ${t.weight};`,
  ]),
  ...Object.entries(space).map(([k, v]) => `  --space-${k}: ${v / 16}rem;`),
  ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
  ...Object.entries(material).flatMap(([k, m]) => [
    `  --blur-${k}: ${m.blur}px;`,
    `  --saturate-${k}: ${m.saturate}%;`,
  ]),
].join("\n");

const css = `/* GENERATED by tokens/build-css.mjs from tokens.js. Do not edit by hand. */
:root {
${staticVars}
${colorVars("light")}
${glassVars("light")}
  color-scheme: light dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars("dark", "    ")}
${glassVars("dark", "    ")}
  }
}
:root[data-theme="dark"] {
${colorVars("dark")}
${glassVars("dark")}
}
body {
  font: var(--text-body-weight) var(--text-body-size) / var(--text-body-leading) var(--font);
  letter-spacing: var(--text-body-tracking);
  color: var(--ink);
  background: var(--canvas);
}
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "tokens.css");
writeFileSync(out, css);
console.log("wrote", out);
